#!/usr/bin/env node
/**
 * Runs a command with local Android build prerequisites:
 * - org.gradle.java.home + JAVA_HOME → JDK 17 (CMake fails on JDK 24+)
 * - ANDROID_HOME / ANDROID_SDK_ROOT → Android SDK
 * - android/local.properties → sdk.dir (gitignored, removed by prebuild --clean)
 */
const { spawnSync } = require('child_process');
const fs = require('fs');
const path = require('path');
const { resolveJdk17Home } = require('./resolve-jdk17');

const PROJECT_ROOT = path.resolve(__dirname, '..');

function resolveAndroidSdk() {
  const fromEnv = process.env.ANDROID_HOME || process.env.ANDROID_SDK_ROOT;
  if (fromEnv && fs.existsSync(path.join(fromEnv, 'platform-tools'))) {
    return fromEnv;
  }

  const home = process.env.HOME || process.env.USERPROFILE || '';
  const defaults = [
    path.join(home, 'Library', 'Android', 'sdk'),
    path.join(home, 'Android', 'Sdk'),
    process.env.LOCALAPPDATA
      ? path.join(process.env.LOCALAPPDATA, 'Android', 'Sdk')
      : undefined,
  ].filter(Boolean);

  for (const candidate of defaults) {
    if (fs.existsSync(path.join(candidate, 'platform-tools'))) {
      return candidate;
    }
  }

  console.error(
    [
      'Android SDK not found.',
      'Install Android Studio or the command-line tools, then either:',
      '  export ANDROID_HOME="$HOME/Library/Android/sdk"   # macOS default',
      'or add sdk.dir to android/local.properties.',
    ].join('\n'),
  );
  process.exit(1);
}

function upsertPropertyFile(filePath, key, value) {
  if (!fs.existsSync(filePath)) {
    return;
  }

  const line = `${key}=${value}`;
  let content = fs.readFileSync(filePath, 'utf8');

  if (new RegExp(`^${key}=`, 'm').test(content)) {
    content = content.replace(new RegExp(`^${key}=.*$`, 'm'), line);
  } else {
    content = `${content.trimEnd()}\n${line}\n`;
  }

  fs.writeFileSync(filePath, content, 'utf8');
}

function ensureLocalProperties(sdkPath) {
  const localPropertiesPath = path.join(PROJECT_ROOT, 'android', 'local.properties');
  const escapedSdkPath = sdkPath.replace(/\\/g, '\\\\');
  const content = `## Auto-generated by scripts/with-android-build-env.js — do not commit.\nsdk.dir=${escapedSdkPath}\n`;
  fs.writeFileSync(localPropertiesPath, content, 'utf8');
}

function ensureGradleJavaHome(javaHome) {
  const escapedJavaHome = javaHome.replace(/\\/g, '\\\\');
  upsertPropertyFile(
    path.join(PROJECT_ROOT, 'android', 'gradle.properties'),
    'org.gradle.java.home',
    escapedJavaHome,
  );
}

const [command, ...args] = process.argv.slice(2);
if (!command) {
  console.error('Usage: node scripts/with-android-build-env.js <command> [args...]');
  process.exit(1);
}

const javaHome = resolveJdk17Home();
if (!javaHome) {
  console.error(
    'JDK 17 is required for Android builds. Install it with: brew install openjdk@17',
  );
  process.exit(1);
}

const androidSdk = resolveAndroidSdk();
ensureLocalProperties(androidSdk);
ensureGradleJavaHome(javaHome);

const result = spawnSync(command, args, {
  stdio: 'inherit',
  env: {
    ...process.env,
    JAVA_HOME: javaHome,
    ANDROID_HOME: androidSdk,
    ANDROID_SDK_ROOT: androidSdk,
  },
  shell: process.platform === 'win32',
});

process.exit(result.status ?? 1);
